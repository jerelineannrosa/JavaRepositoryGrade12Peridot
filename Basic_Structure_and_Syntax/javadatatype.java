package Basic_Structure_and_Syntax;

public class javadatatype {
    public static void main(String[] args) {
        System.out.println("Java Data Type Activity");
        byte playerlevel = 12;
        System.out.println("Player Level: " + playerlevel);
        short playerMaxHp = 5000;
        System.out.println("Player Max HP: " + playerMaxHp);
        int gameScore = 145820;
        System.out.println("Game Score: " + gameScore);
        long gamePlayTimeMs = 86400000l;
        System.out.println("Game Play Time (ms): " + gamePlayTimeMs);
        float playerSpeed = 5.75f;
        System.out.println("Player Speed: " + playerSpeed);
        double playerExactXCoordinate = 142.8594023d;
        System.out.println("Player Exact X Coordinate: " + playerExactXCoordinate);
        double playerExactYCoordinate = 98.4567890123d;
        System.out.println("Player Exact Y Coordinate: " + playerExactYCoordinate);
        float playerHealthPercentage = 75.5f;
        System.out.println("Player Health Percentage: " + playerHealthPercentage);
        boolean isPlayerAlive = true;
        System.out.println("Is Player Alive: " + isPlayerAlive);
        char playerRank = 'A';
        System.out.println("Player Rank: " + playerRank);   
        char playerVar1 = 118, playerVar2 = 120, playerVar3 = 117;
        System.out.println("Player Var1: " + playerVar1);
        System.out.println("Player Var2: " + playerVar2);
        System.out.println("Player Var3: " + playerVar3);

    }
}
