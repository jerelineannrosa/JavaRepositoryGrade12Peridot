package Basic_Structure_and_Syntax;

public class Datatype {
    public static void main(String[] args) {
       System.out.println("Activity # 2 - Java Datatypes");
       byte myByte = 127;
       System.out.println("Byte Value: " + myByte);
       short myShort = 18674;
       System.out.println("Short Value: " + myShort);
       int myInt = 276384936;
       System.out.println("Integer Value: " + myInt);
       long myLong = 1234567890123l;
       System.out.println("Long Value: " + myLong);
       float myFloat = 9.67f;
       System.out.println("Float Value: " + myFloat);
       double myDouble = 25.65d;
       System.out.println("Double Value: " + myDouble);
       float myScientificFloat = 3.58e3f; //3.58 x 10^3
       System.out.println("Scientific Notation Float Value: " + myScientificFloat);
       double myScientificDouble = 4.56e-2d; //4.56 x 10^-2
       System.out.println("Scientific Notation Double Value: " + myScientificDouble);
       boolean myBoolean = true;
       System.out.println("Boolean Value: " + myBoolean);
       char myChar = 'A';
       System.out.println("Character Value: " + myChar);
       char myVar1 = 123, myVar2 = 125, myVar3 = 121;
       System.out.println(myVar1);
       System.out.println(myVar2);
       System.out.println(myVar3);
       String myNull = null;
       System.out.println("Null value: " + myNull);
    }
}
